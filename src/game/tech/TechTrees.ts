export function getTechTree(faction: FactionId): FactionTechTree {
  return TECH_TREES[faction];
}

export function getTechNode(faction: FactionId, nodeId: string): TechNode | undefined {
  return TECH_TREES[faction].nodes.find((n) => n.id === nodeId);
}

export function initiallyLockedUnitIds(faction: FactionId): Set<number> {
  const locked = new Set<number>();
  for (const node of TECH_TREES[faction].nodes) {
    if (node.kind === 'unitUnlock' && node.unlocksUnits) {
      for (const id of node.unlocksUnits) locked.add(id);
    }
  }
  return locked;
}

export function initiallyLockedBuildingIds(faction: FactionId): Set<number> {
  const locked = new Set<number>();
  for (const node of TECH_TREES[faction].nodes) {
    if (node.kind === 'buildingUnlock' && node.unlocksBuildings) {
      for (const id of node.unlocksBuildings) locked.add(id);
    }
  }
  return locked;
}
