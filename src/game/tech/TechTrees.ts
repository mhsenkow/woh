import { FactionId } from '../../sim/ecs/components';

/**
 * Tech tree node kinds map to what unlocking does in sim systems.
 * - unitUnlock / buildingUnlock gate production lists
 * - upgrade mutates combat / economy stats
 * - abilityUnlock adds a command-card special
 * - passive is always-on once researched (creep regen, pipe capacity…)
 */
export type TechNodeKind =
  | 'unitUnlock'
  | 'buildingUnlock'
  | 'upgrade'
  | 'abilityUnlock'
  | 'passive';

export interface TechCost {
  primary: number;
  secondary?: number;
}

export interface TechEffect {
  stat?: string;
  delta?: number;
  mode?: 'add' | 'mul';
  targetIds?: number[];
  payload?: Record<string, number | string | boolean | number[]>;
}

export interface TechNode {
  id: string;
  name: string;
  description: string;
  kind: TechNodeKind;
  tier: 1 | 2 | 3;
  researchedAt: number;
  cost: TechCost;
  researchTime: number;
  requires: string[];
  unlocksUnits?: number[];
  unlocksBuildings?: number[];
  effect?: TechEffect;
  hotkey?: string;
}

export interface FactionTechTree {
  faction: FactionId;
  name: string;
  thesis: string;
  tier2GateBuilding: number;
  tier3GateBuilding: number;
  nodes: TechNode[];
}

